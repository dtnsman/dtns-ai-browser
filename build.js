/**
 * build.js — bundles src/ into a single ESM file for MV3 service workers.
 *
 * No external dependencies: every module in src/ only uses static relative
 * `require()` calls, so a tiny registry + rewrite is enough. The result is a
 * self-contained module that a service worker can `import` directly.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const OUTPUT = path.join(DIST, 'dtns-browser-proxy.mjs');
// The loadable extension vendors the same bundle under a .js name so the MV3
// service worker import resolves without relying on .mjs MIME handling.
const VENDOR = path.join(ROOT, 'extension', 'vendor', 'dtns-browser-proxy.js');

function listSources(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listSources(full));
    else if (entry.name.endsWith('.js')) out.push(full);
  }
  return out.sort();
}

function moduleId(file) {
  return path.relative(SRC, file).split(path.sep).join('/').replace(/\.js$/, '');
}

function resolveRequest(request, file) {
  if (request.charAt(0) !== '.') {
    throw new Error('Unexpected external require("' + request + '") in ' + file);
  }
  const resolved = path.resolve(path.dirname(file), request);
  const id = moduleId(resolved.endsWith('.js') ? resolved : resolved + '.js');
  if (!fs.existsSync(path.join(SRC, id + '.js'))) {
    throw new Error('Cannot resolve require("' + request + '") from ' + file);
  }
  return id;
}

/**
 * Rewrite `require('./x')` into `__require('x')`, skipping comments and string
 * literals so that documentation examples are not rewritten by accident.
 */
function rewriteRequires(code, file) {
  const REQUIRE = /^require\(\s*(['"])([^'"]+)\1\s*\)/;
  let out = '';
  let i = 0;

  while (i < code.length) {
    const ch = code[i];
    const next = code[i + 1];

    if (ch === '/' && next === '/') {
      const end = code.indexOf('\n', i);
      const stop = end === -1 ? code.length : end;
      out += code.slice(i, stop);
      i = stop;
      continue;
    }

    if (ch === '/' && next === '*') {
      const end = code.indexOf('*/', i + 2);
      const stop = end === -1 ? code.length : end + 2;
      out += code.slice(i, stop);
      i = stop;
      continue;
    }

    if (ch === '"' || ch === "'" || ch === '`') {
      let j = i + 1;
      while (j < code.length) {
        if (code[j] === '\\') { j += 2; continue; }
        if (code[j] === ch) { j += 1; break; }
        j += 1;
      }
      out += code.slice(i, j);
      i = j;
      continue;
    }

    const isRequire = code.startsWith('require', i) &&
      !/[A-Za-z0-9_$.]/.test(code.charAt(i - 1));
    if (isRequire) {
      const match = REQUIRE.exec(code.slice(i));
      if (match) {
        out += '__require(' + JSON.stringify(resolveRequest(match[2], file)) + ')';
        i += match[0].length;
        continue;
      }
    }

    out += ch;
    i += 1;
  }

  return out;
}

function build() {
  const files = listSources(SRC);
  const parts = [];

  parts.push('/* DTNS browser proxy — generated by build.js, do not edit. */');
  parts.push('const __modules = Object.create(null);');
  parts.push('const __cache = Object.create(null);');
  parts.push('function __define(id, factory) { __modules[id] = factory; }');
  parts.push('function __require(id) {');
  parts.push('  if (__cache[id]) return __cache[id].exports;');
  parts.push('  const module = { exports: {} };');
  parts.push('  __cache[id] = module;');
  parts.push('  __modules[id](module, module.exports, __require);');
  parts.push('  return module.exports;');
  parts.push('}');

  for (const file of files) {
    const id = moduleId(file);
    const code = rewriteRequires(fs.readFileSync(file, 'utf8'), file);
    parts.push('__define(' + JSON.stringify(id) + ', function (module, exports, __require) {');
    parts.push(code);
    parts.push('});');
  }

  // The public surface is whatever src/index.js exports, so the bundle can
  // never drift from the source entry point.
  const publicApi = Object.keys(require(path.join(SRC, 'index.js')));
  parts.push('const __api = __require("index");');
  parts.push('export const version = __api.version;');
  for (const name of publicApi) {
    if (name === 'version') continue;
    parts.push('export const ' + name + ' = __api.' + name + ';');
  }
  parts.push('export default __api;');

  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(OUTPUT, parts.join('\n') + '\n', 'utf8');

  // Mirror into the extension so `npm run build` keeps the loadable copy fresh.
  fs.mkdirSync(path.dirname(VENDOR), { recursive: true });
  fs.copyFileSync(OUTPUT, VENDOR);
  // Chrome ignores this marker; Node uses it to treat the bundle as ESM when
  // tooling imports extension/vendor directly (e.g. the packaging tests).
  fs.writeFileSync(
    path.join(path.dirname(VENDOR), 'package.json'),
    JSON.stringify({ type: 'module', private: true }, null, 2) + '\n',
    'utf8'
  );

  const bytes = fs.statSync(OUTPUT).size;
  console.log('built ' + path.relative(ROOT, OUTPUT));
  console.log('  modules: ' + files.length);
  console.log('  exports: ' + (publicApi.length + 1));
  console.log('  size: ' + (bytes / 1024).toFixed(1) + ' KiB');
  console.log('vendored ' + path.relative(ROOT, VENDOR));
  return OUTPUT;
}

if (require.main === module) {
  build();
}

module.exports = { build, OUTPUT, VENDOR, moduleId, rewriteRequires };
